"""python -m price_forecast.funding: run the pre-registered funding event study."""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

from price_forecast.data.candles import BTC_USD_DAILY_CSV, read_candles
from price_forecast.funding.features import build_features
from price_forecast.funding.fetch import FUNDING_DIR, VENUES, load_venue
from price_forecast.funding.study import HORIZONS, render_report, run_study

OUT = Path(__file__).resolve().parents[2] / "results" / "funding" / "event_study.md"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, default=BTC_USD_DAILY_CSV, help="Coinbase daily candle CSV")
    parser.add_argument("--funding-dir", type=Path, default=FUNDING_DIR)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)

    candles = read_candles(args.csv)
    closes = {c.day: c.close for c in candles}
    prints = {venue: load_venue(venue, args.funding_dir) for venue in VENUES}
    features = build_features(prints)
    res = run_study(closes, features)

    first_print = {v: datetime.fromtimestamp(p[0].time_ms / 1000, timezone.utc).date() for v, p in prints.items()}
    header = "\n".join(
        [
            "# Funding-rate event study",
            "",
            "Not investment advice. Measurement only: no strategy, no backtest.",
            "",
            "- Generated by `python -m price_forecast.funding` (design: [preregistration.md](preregistration.md)).",
            f"- BTC prices: Coinbase daily closes {candles[0].day} → {candles[-1].day} (`data/btc-usd-daily.csv`).",
            "- Funding: "
            + ", ".join(f"`{v}` from {d}" for v, d in first_print.items())
            + ". 8h prints, daily rate = 3 × mean of the UTC day's prints; feature = trailing 7-day mean.",
            f"- Horizons {', '.join(f'{h}d' for h in HORIZONS)}: close(D+h)/close(D) − 1, entered at the signal day's close.",
        ]
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_report(res, header=header), encoding="utf-8")
    summary = {
        "verdict": res.verdict,
        "incremental": res.incremental,
        "cells": [
            {
                "feature": c.feature,
                "horizon": c.horizon,
                "n": c.n,
                "spread": c.buckets.spread,
                "spread_t": c.buckets.spread_t,
                "spread_p": c.buckets.spread_p,
                "spread_holm_p": float(res.spread_holm[k]),
                "spearman": c.buckets.spearman,
                "slope_t": c.slope.t,
                "incremental_t": c.incremental.t,
            }
            for k, c in res.cells.items()
        ],
    }
    args.out.with_suffix(".json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(f"{res.verdict} (incremental: {res.incremental}) -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
